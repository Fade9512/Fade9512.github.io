const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const context = vm.createContext({document:{querySelector:()=>({})},localStorage:{getItem:()=>null}});
const data = fs.readFileSync(path.join(root,fs.existsSync(path.join(root,'dist'))?'dist/data.js':'data.js'),'utf8');
const app = fs.readFileSync(path.join(root,fs.existsSync(path.join(root,'dist'))?'dist/app.js':'app.js'),'utf8');
vm.runInContext(data+'\n'+app.slice(0,app.indexOf("document.addEventListener('click'")),context);
const run = code => vm.runInContext(code,context);
assert.equal(run('MODELS.length'),14);
assert.equal(run('new Set(MODELS.map(m=>m.id)).size'),14);
assert.equal(run('MODELS.every(m=>m.math.length>=2 && m.exercise.length===3 && m.sources.every(s=>SOURCES[s]) && m.python && m.matlab && m.validation && m.condition && m.pitfall)'),true);
const top = p => run(`ranking({...DEFAULT_PROFILE,...${JSON.stringify(p)}})[0]?.model.id`);
assert.equal(top({}),'regression');
assert.equal(top({goal:'optimize',data:'network',features:['integer','constraints']}),'linearprog');
assert.equal(top({goal:'dynamics',data:'mechanism',features:['interpret','nonlinear']}),'ode');
assert.equal(top({goal:'predict',data:'time',features:['uncertain']}),'timeseries');
assert.equal(top({goal:'evaluate',data:'indicators',features:['interpret']}),'evaluation');
assert.equal(top({goal:'classify',data:'table',features:[],labels:false}),'clustering');
assert.equal(top({goal:'classify',data:'table',features:['interpret'],labels:true}),'classification');
assert.equal(top({goal:'predict',data:'table',labels:false}),undefined);
assert.equal(top({goal:'predict',data:'time',labels:false}),undefined);
assert.equal(top({goal:'predict',data:'none'}),undefined);
assert.equal(top({goal:'inference',data:'none'}),undefined);
let count=0;
for (const goal of run('GOALS.map(x=>x.id)')) for(const dataType of run('DATA_TYPES.map(x=>x.id)')) for(let mask=0;mask<64;mask++) for(const labels of [true,false]) for(const experience of ['beginner','basic']){
 const features=run('FEATURES.map(x=>x.id)').filter((_,i)=>mask&(1<<i));
 const p={goal,data:dataType,features,labels,experience};
 const out=run(`ranking({...DEFAULT_PROFILE,...${JSON.stringify(p)}}).map(x=>({id:x.model.id,score:x.score}))`);
 assert(out.length<=3);
 assert.equal(new Set(out.map(x=>x.id)).size,out.length);
 assert(out.every(x=>Number.isFinite(x.score)));
 if(!labels&&goal==='classify')assert(!out.some(x=>['ensemble','classification'].includes(x.id)));
 if(labels&&goal==='classify')assert(!out.some(x=>x.id==='clustering'));
 if(!labels&&goal==='predict'&&['table','time','indicators'].includes(dataType))assert.equal(out.length,0);
 count++;
}
console.log(`PASS: 14 model records, 11 scenario/guard checks, ${count} input combinations.`);
